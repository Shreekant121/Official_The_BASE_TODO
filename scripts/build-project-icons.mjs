/*
 * Writes the icons a project can wear (29-1P8a2, idea 150) — two files:
 *
 *   node scripts/build-project-icons.mjs      (npm run build:project-icons)
 *
 * - `src/lib/projectIcons/catalog.generated.ts` — EVERY Phosphor glyph, fill
 *   weight, with its search words: 1,512 of them, ~0.6 MB of path data. Only
 *   ever reached through `import()` (`lib/projectIcons/glyphs.ts`), so it is
 *   its own chunk, fetched the first time the picker opens or a card wears an
 *   icon this device has not drawn yet — never part of the startup download
 *   (CLAUDE.md "Performance", rule 7).
 * - `src/lib/projectIcons/starter.generated.ts` — the few glyphs a project
 *   wears without choosing (a new project's, and the one a project with no
 *   icon shows), bundled, so a default never waits for the catalogue.
 *
 * His call, 2026-10-13: "a white icon (Phosphor, searchable by name)". Fill is
 * the weight because a white glyph on frosted glass is what V3's `<Icon>`
 * draws (`build-phosphor.mjs`), and the whole set because he asked to search
 * it, not to scroll a shortlist. Brands are in: a project can be a channel.
 *
 * The catalogue is a JSON string handed to `JSON.parse`: V8 parses a big JSON
 * string several times faster than the same data as a JS literal, which is
 * what the tablet pays the first time it opens the picker.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CORE = join(ROOT, 'node_modules', '@phosphor-icons', 'core');
const OUT_DIR = join(ROOT, 'src', 'lib', 'projectIcons');

/* Keep in step with `DEFAULT_PROJECT_ICON` and `FALLBACK_PROJECT_ICON` in `lib/projectIcon.ts`. */
const STARTER = ['rocket-launch', 'clipboard-text'];

const { icons } = await import(new URL(`file:///${join(CORE, 'dist', 'index.mjs').replace(/\\/g, '/')}`).href);

function pathsOf(name) {
  const svg = readFileSync(join(CORE, 'assets', 'fill', `${name}-fill.svg`), 'utf8');
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const paths = [...inner.matchAll(/<path d="([^"]+)"\/>/g)].map((m) => m[1]);
  if (paths.length === 0 || inner.replace(/<path d="[^"]+"\/>/g, '') !== '') {
    throw new Error(`[build-project-icons] ${name}-fill.svg holds something other than <path d>`);
  }
  return paths;
}

/* Phosphor's bookkeeping tags ("*new*", "*updated*") are not words he would type. */
const words = (tags) => [...new Set(tags.filter((t) => !t.startsWith('*')).map((t) => t.toLowerCase()))].join(' ');

const rows = [...icons]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((i) => [i.name, words([...i.tags, ...i.categories]), pathsOf(i.name)]);

const json = JSON.stringify(rows);
/* A few tags carry an apostrophe ("rock 'n' roll"): escaped for the single-quoted literal. */
const literal = json.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  join(OUT_DIR, 'catalog.generated.ts'),
  `/* GENERATED by scripts/build-project-icons.mjs (npm run build:project-icons) — do not edit by hand.
   Every Phosphor glyph (MIT, @phosphor-icons/core), fill weight, in its 256-unit
   viewBox: [name, search words, paths]. Imported only through \`import()\`. */
export type CatalogRow = readonly [name: string, words: string, paths: readonly string[]];
export const CATALOG: readonly CatalogRow[] = JSON.parse('${literal}');
`,
);

const starter = Object.fromEntries(STARTER.map((n) => [n, pathsOf(n)]));
writeFileSync(
  join(OUT_DIR, 'starter.generated.ts'),
  `/* GENERATED by scripts/build-project-icons.mjs (npm run build:project-icons) — do not edit by hand.
   The glyphs a project wears without choosing, bundled so they never wait. */
export const STARTER_GLYPHS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(starter, null, 2)};
`,
);

console.log(`[build-project-icons] ${rows.length} glyphs in the catalogue (${Math.round(json.length / 1024)} KB), ${STARTER.length} bundled`);
