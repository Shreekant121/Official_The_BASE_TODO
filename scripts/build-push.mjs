/**
 * Bundles the push sender into one file a Vercel function can load — BUILD-5.
 *
 *   node scripts/build-push.mjs          writes api/_lib/pushRun.js and keyAccess.js
 *   node scripts/build-push.mjs --check  fails if either file is stale
 *
 * Why it exists at all is at the top of `server/pushRun.ts`: the sender runs
 * the app's own rule out of `src/`, whose extensionless imports Node refuses
 * once Vercel has compiled each file separately. One bundled file has no
 * relative imports left to refuse.
 *
 * **The output is committed**, and `npm run build` runs the check. Vercel
 * builds a function from the files it was handed, so a stale bundle is a
 * sender quietly running yesterday's rule — the check turns that into a
 * failed build instead.
 *
 * Every npm package stays an ordinary `import` (`packages: 'external'`), so
 * Vercel's file tracer finds `firebase-admin`, `web-push` and `zustand` in
 * `node_modules` exactly as it does for the other functions. Only this app's
 * own source is inlined.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

/*
 * BUILD-6 added the second bundle: the lock on the Gemini key, which three
 * routes share and which asks `src/lib/adminAccess.ts` — the same rule the
 * browser reads — so it has the same extensionless-import problem.
 */
const BUNDLES = [
  { entry: 'server/pushRun.ts', out: 'api/_lib/pushRun.js' },
  { entry: 'server/keyAccess.ts', out: 'api/_lib/keyAccess.js' },
];

/* Line endings are normalised both ways: this repo is checked out with CRLF
   conversion on the laptop, and a byte comparison would fail on that alone. */
const lf = (text) => text.replace(/\r\n/g, '\n');

let stale = false;

for (const { entry, out } of BUNDLES) {
  const outfile = resolve(root, out);
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    packages: 'external',
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
    banner: {
      js: `// GENERATED by scripts/build-push.mjs from ${entry}. Do not edit; run \`npm run build:push\`.`,
    },
  });
  const fresh = lf(result.outputFiles[0].text);

  if (check) {
    let current = '';
    try {
      current = lf(readFileSync(outfile, 'utf8'));
    } catch {
      current = '';
    }
    if (current !== fresh) {
      console.error(
        `\n${out} is out of date with ${entry} or the src/ files it bundles.\n` +
          'Run `npm run build:push` and commit the result.\n',
      );
      stale = true;
    } else {
      console.log(`${out} is current`);
    }
  } else {
    mkdirSync(dirname(outfile), { recursive: true });
    writeFileSync(outfile, fresh);
    console.log(`wrote ${outfile} (${fresh.length} bytes)`);
  }
}

if (stale) process.exit(1);
