/**
 * Bundles Atlas's own code for the tablet — BIG-12.
 *
 *   node scripts/build-atlas-engine.mjs          writes both bundles below
 *   node scripts/build-atlas-engine.mjs --check  fails if either is stale
 *   node scripts/build-atlas-engine.mjs --report prints what is in the engine, largest first
 *
 * With the laptop shut the tablet runs Atlas itself: the same `runChat` the
 * laptop serves `/chat` with, from `../atlas/src/browser/engine.ts`. It is
 * Atlas's code and stays in Atlas's repository — this app never holds a
 * second copy of the loop (the thing BIG-1 refused as "rebuilding Atlas
 * twice"). Three substitutions make it run in a page:
 *
 * - `node:fs` and `node:path` become `atlas/src/browser/memfs.ts` and
 *   `path.ts`, an in-memory disk the engine fills from BIG-4's cloud copy;
 * - `node:dns/promises` becomes `dnsStub.ts` — the web tools are bundled, but
 *   a page is fetched by the route below, never from the browser (27A-4);
 * - `process.pid`, read once when a store writes a file, becomes `0`.
 *
 * **The second bundle is the server half of web lookup (27A-4)**:
 * `../atlas/src/lookup/remote.ts` for `api/lookup.ts` — fetching a page with
 * Atlas's own private-address guard, and one Brave search — bundled for Node
 * because an `api/` function cannot import across folders on Vercel (the same
 * reason as `build-push.mjs`).
 *
 * **The output is committed, and `npm run build` runs the check** — the same
 * arrangement as `build-push.mjs`, for a sharper reason: Vercel builds from the
 * uploaded `liquid-glass/` folder and never sees `../atlas`, so the bundles are
 * the only way the code gets there. Where `../atlas` is absent (Vercel), the
 * check says so and passes; on the laptop a stale bundle fails the build.
 *
 * The app imports the engine with `import()`, only for a lid-shut turn, so none
 * of it is in the startup download (CLAUDE.md, Performance rule 7).
 */
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const atlas = resolve(root, '..', 'atlas');
const check = process.argv.includes('--check');
const report = process.argv.includes('--report');

const BUNDLES = [
  {
    entry: 'src/browser/engine.ts',
    out: 'src/lib/atlas/engine/atlasEngine.generated.js',
    options: {
      platform: 'browser',
      target: 'es2022',
      alias: {
        'node:fs': resolve(atlas, 'src/browser/memfs.ts'),
        'node:path': resolve(atlas, 'src/browser/path.ts'),
        'node:dns/promises': resolve(atlas, 'src/browser/dnsStub.ts'),
      },
      define: { 'process.pid': '0' },
    },
  },
  {
    entry: 'src/lookup/remote.ts',
    out: 'api/_lib/lookup.js',
    options: { platform: 'node', target: 'node20', packages: 'external' },
  },
];

/* Line endings are normalised both ways, as in build-push.mjs: the repo is
   checked out with CRLF conversion on the laptop. */
const lf = (text) => text.replace(/\r\n/g, '\n');

if (!existsSync(resolve(atlas, BUNDLES[0].entry))) {
  if (check) {
    console.log('../atlas is not here (a Vercel build), so the committed Atlas bundles are used as they are.');
    process.exit(0);
  }
  console.error(`Cannot bundle: ${resolve(atlas, BUNDLES[0].entry)} does not exist. Atlas's repository must sit beside this one.`);
  process.exit(1);
}

let stale = false;

for (const { entry, out, options } of BUNDLES) {
  const outfile = resolve(root, out);
  const result = await build({
    absWorkingDir: atlas,
    entryPoints: [resolve(atlas, entry)],
    bundle: true,
    format: 'esm',
    write: false,
    metafile: report,
    legalComments: 'none',
    logLevel: 'warning',
    ...options,
    banner: {
      js: `// GENERATED by scripts/build-atlas-engine.mjs from ../atlas/${entry}. Do not edit; run \`npm run build:atlas\`.`,
    },
  });

  const fresh = lf(result.outputFiles[0].text)
    // esbuild writes absolute source paths into its module comments; the
    // laptop's folder name has no business in a committed file, and a
    // different checkout location must not make the bundle "stale".
    .replaceAll(lf(atlas).replace(/\\/g, '/'), '<atlas>')
    .replace(/^\/\/ (?!GENERATED).*[\\/]atlas[\\/].*$/gm, (line) => line.replace(/\\/g, '/'));

  if (report && entry === BUNDLES[0].entry) {
    const inputs = Object.entries(result.metafile.inputs).sort((a, b) => b[1].bytes - a[1].bytes);
    console.log(`${fresh.length} bytes unminified, from ${inputs.length} files. Largest:`);
    for (const [file, info] of inputs.slice(0, 20)) console.log(`  ${String(info.bytes).padStart(8)}  ${relative(atlas, resolve(atlas, file))}`);
  }

  if (check) {
    let current = '';
    try {
      current = lf(readFileSync(outfile, 'utf8'));
    } catch {
      current = '';
    }
    if (current !== fresh) {
      console.error(
        `\n${out} is out of date with ../atlas/${entry} or the Atlas files it bundles.\n` +
          'Run `npm run build:atlas` and commit the result.\n',
      );
      stale = true;
    } else {
      console.log(`${out} is current`);
    }
  } else {
    mkdirSync(dirname(outfile), { recursive: true });
    writeFileSync(outfile, fresh);
    console.log(`wrote ${out} (${fresh.length} bytes)`);
  }
}

if (stale) process.exit(1);
