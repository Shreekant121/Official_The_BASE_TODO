import React from 'react';
import { AbsoluteFill, Audio, Sequence, staticFile, useVideoConfig } from 'remotion';
import { GlassDefs, Grain } from './components/primitives';
import { C, FONT } from './theme';
import { Chaos } from './scenes/Chaos';
import { Logo } from './scenes/Logo';
import { Board } from './scenes/Board';
import { ScoreScene } from './scenes/ScoreScene';
import { SmartStart } from './scenes/SmartStart';
import { Focus } from './scenes/Focus';
import { Agent } from './scenes/Agent';
import { Everywhere } from './scenes/Everywhere';
import { Finale } from './scenes/Finale';

export const PROMO_SECONDS = 90;

/** Scene timeline, in seconds. Neighbours overlap so each can hand over. */
export const TIMELINE: { id: string; from: number; dur: number; C: React.FC }[] = [
  { id: 'chaos', from: 0, dur: 8.5, C: Chaos },
  { id: 'logo', from: 8, dur: 6.5, C: Logo },
  { id: 'board', from: 14, dur: 10.5, C: Board },
  { id: 'score', from: 24, dur: 12.5, C: ScoreScene },
  { id: 'smart', from: 36, dur: 11.5, C: SmartStart },
  { id: 'focus', from: 47, dur: 10.5, C: Focus },
  { id: 'agent', from: 57, dur: 16.5, C: Agent },
  { id: 'everywhere', from: 73, dur: 10.5, C: Everywhere },
  { id: 'finale', from: 83, dur: 7, C: Finale },
];

export const Promo: React.FC = () => {
  const { fps } = useVideoConfig();
  return (
    <AbsoluteFill style={{ background: 'black', color: C.fg1, fontFamily: FONT, WebkitFontSmoothing: 'antialiased' }}>
      <GlassDefs />
      {TIMELINE.map(({ id, from, dur, C }) => (
        <Sequence key={id} name={id} from={Math.round(from * fps)} durationInFrames={Math.round(dur * fps)}>
          <C />
        </Sequence>
      ))}
      <Grain />
      {/* Generated by `npm run audio` (scripts/soundtrack.mjs). */}
      <Audio src={staticFile('soundtrack.wav')} />
    </AbsoluteFill>
  );
};
